void LoadLeaderboard()                                      //loading data from leaderboard.txt file
{
    FILE *file = fopen("leaderboard.txt", "r");
    leaderboardCount = 0;
    if(file == NULL) return;
    while(leaderboardCount < MAX_LEADERBOARD && fscanf(file, " %29[^|]|%d",leaderboard[leaderboardCount].name,&leaderboard[leaderboardCount].score) == 2)
    {
        leaderboardCount++;
    }
    fclose(file);
}
void SaveLeaderboard()                                      //Adding name and score to leaderboard.txt file
{
    FILE *file = fopen("leaderboard.txt", "w");
    if(file == NULL) return;
    for(int i = 0; i < leaderboardCount; i++)
    {
        fprintf(file, "%s|%d\n",leaderboard[i].name,leaderboard[i].score);
    }
    fclose(file);
}
void reset_leaderboard()
{
    leaderboardCount=0;
    SaveLeaderboard();
}
void AddLeaderboardScore(const char *name, int newScore)         //Add any new score to leaderboard in descending order       
{
    int position = 0;
    while(position < leaderboardCount && leaderboard[position].score >= newScore)
    {
        position++;
    }
    if(position >= MAX_LEADERBOARD) return;
    int limit = leaderboardCount;
    if(limit == MAX_LEADERBOARD) limit = MAX_LEADERBOARD - 1;
    for(int i = limit; i > position; i--)
    {
        leaderboard[i] = leaderboard[i - 1];
    }
    strncpy(leaderboard[position].name, name, MAX_NAME_LENGTH - 1);
    leaderboard[position].name[MAX_NAME_LENGTH - 1] = '\0';
    leaderboard[position].score = newScore;
    if(leaderboardCount < MAX_LEADERBOARD) leaderboardCount++;
    SaveLeaderboard();
}

bool collisionCheck(Rectangle playerRec, Rectangle walls[], int wallCount)    //collision check function
{                                                                             
    for(int i = 0; i < wallCount; i++)
    {
        if(walls[i].y<40) continue;
        if(CheckCollisionRecs(playerRec, walls[i])) return true;
    }
    return false;
}
int createWalls(int maze[32][40], Rectangle walls[120])                       //creating walls function
{
    int wallCount = 0;
    for(int i = 0; i < 32; i++)
    {
        for(int j = 0; j < 40; j++)
        {
            if(maze[i][j] == 1)
            {
                walls[wallCount] = (Rectangle){j * 20, i * 20, 20, 20};
                wallCount++;
            }
        }
    }
    return wallCount;
}
